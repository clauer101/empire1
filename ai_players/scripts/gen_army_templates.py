#!/usr/bin/env python3
"""Generate bot-local army templates from the server's ai_waves.yaml.

The attack bot builds its army toward an era-matched template (wave count,
slots per wave, critter types). Rather than read python_server's config at
runtime (fragile cross-repo path), this script condenses ai_waves.yaml into
a self-contained bot-local file: one representative army per era.

Run from the repo root:

    python ai_players/scripts/gen_army_templates.py

Writes ai_players/config/army_templates.yaml (committed to the repo).
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC = REPO_ROOT / "python_server" / "config" / "ai_waves.yaml"
DST = REPO_ROOT / "ai_players" / "config" / "army_templates.yaml"

# ai_waves.yaml era section headers (UPPERCASE) → bot era keys (lowercase,
# matching ERA_RANK in bot/analyzer.py).
ERA_HEADER_TO_KEY = {
    "STONE_AGE": "stone",
    "NEOLITHIC": "neolithic",
    "BRONZE_AGE": "bronze",
    "IRON_AGE": "iron",
    "MIDDLE_AGES": "middle_ages",
    "RENAISSANCE": "renaissance",
    "INDUSTRIAL": "industrial",
    "MODERN": "modern",
    "FUTURE": "future",
}

_HEADER_RE = re.compile(r"^\s*#\s+(" + "|".join(ERA_HEADER_TO_KEY) + r")\b")


def _split_by_era(text: str) -> dict[str, list[str]]:
    """Bucket the raw line ranges of ai_waves.yaml by era section header."""
    buckets: dict[str, list[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        m = _HEADER_RE.match(line)
        if m:
            current = ERA_HEADER_TO_KEY[m.group(1)]
            buckets.setdefault(current, [])
            continue
        if current is not None:
            buckets[current].append(line)
    return buckets


def _parse_armies(lines: list[str]) -> list[dict]:
    """Parse the army list entries from a bucket of lines."""
    # Re-wrap as a standalone YAML doc; entries are top-level list items ("- ").
    doc = "armies:\n" + "\n".join(lines)
    data = yaml.safe_load(doc) or {}
    return [a for a in (data.get("armies") or []) if a and a.get("waves")]


def _army_slots(army: dict) -> int:
    return sum(int(w.get("slots", 0) or 0) for w in army.get("waves", []))


def _pick_representative(armies: list[dict]) -> dict | None:
    """Median army by total slots (deterministic, mid-sized of the era block)."""
    if not armies:
        return None
    ordered = sorted(armies, key=_army_slots)
    return ordered[len(ordered) // 2]


def main() -> None:
    text = SRC.read_text()
    buckets = _split_by_era(text)

    templates: dict[str, list[dict]] = {}
    for era, lines in buckets.items():
        armies = _parse_armies(lines)
        rep = _pick_representative(armies)
        if rep is None:
            continue
        templates[era] = [
            {"critter": str(w["critter"]).upper(), "slots": int(w["slots"])}
            for w in rep["waves"]
            if w.get("critter") and w.get("slots")
        ]

    DST.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# AUTO-GENERATED by ai_players/scripts/gen_army_templates.py\n"
        "# Source: python_server/config/ai_waves.yaml — do not edit by hand.\n"
        "# One representative army per era (median by total slots). The attack\n"
        "# bot uses these as a target shape: wave count, slots/wave, critter types.\n\n"
    )
    DST.write_text(header + yaml.safe_dump({"templates": templates}, sort_keys=False))
    print(f"Wrote {DST.relative_to(REPO_ROOT)} with {len(templates)} eras.")


if __name__ == "__main__":
    main()
