"""Era-matched army templates derived from the server's ai_waves.yaml.

The attack bot builds its army toward a template for its current era: a target
shape of wave count, slots per wave and preferred critter types. The template
is a loose guideline — missing critters fall back to the strongest unlocked one
of the same era, and after defeats the bot grows beyond the template.

The data file (config/army_templates.yaml) is generated by
scripts/gen_army_templates.py; re-run it when ai_waves.yaml changes.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import yaml

from bot.analyzer import ERA_RANK

_TEMPLATES_PATH = Path(__file__).resolve().parent.parent / "config" / "army_templates.yaml"

# era_rank → era_key, e.g. 2 → "bronze" (inverse of ERA_RANK)
_RANK_TO_ERA = {rank: era for era, rank in ERA_RANK.items()}


@lru_cache(maxsize=1)
def load_templates() -> dict[str, list[dict]]:
    """era_key → list of {"critter": IID, "slots": int} (cached)."""
    if not _TEMPLATES_PATH.exists():
        return {}
    data = yaml.safe_load(_TEMPLATES_PATH.read_text()) or {}
    return data.get("templates") or {}


def template_for_era(era_rank: int,
                     templates: dict[str, list[dict]] | None = None) -> list[dict]:
    """Template for this era rank; clamp down to the nearest lower era present."""
    templates = templates if templates is not None else load_templates()
    if not templates:
        return []
    for rank in range(era_rank, -1, -1):
        era = _RANK_TO_ERA.get(rank)
        if era and templates.get(era):
            return templates[era]
    return []
